export const getCategoryTranslationKey = (name: string): string => {
  const key = categoryKeyMap[name] || name.toLowerCase().replace(/[^a-z0-9]+/g, "_");
  return `category_${key}`;
};

export const translateCategory = (name: string, language: string, t: (key: string) => string): string => {
  const key = getCategoryTranslationKey(name);
  const hasTranslation = !!(translations[language]?.[key] || translations["zh-TW"]?.[key]);
  return hasTranslation ? t(key) : name;
};

export const useTranslation = () => {
  const language = useDownloadStore((state) => state.settings.language) || "zh-TW";
  
  const t = (key: string, variables?: Record<string, string | number>): string => {
    let raw = translations[language]?.[key] || translations["zh-TW"]?.[key] || key;
    if (variables) {
      Object.entries(variables).forEach(([k, v]) => {
        raw = raw.replace(`{${k}}`, String(v));
      });
    }
    return raw;
  };

  return { t, language };
};

