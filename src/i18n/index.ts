export const translateTagGroup = (group: string, language: string): string => {
  if (language === "zh-TW" || !language) return group;
  return groupTranslationMap[group]?.[language] || group;
};

export const translateTagName = (name: string, slug: string, language: string): string => {
  if (language === "zh-TW" || !language) return name;
  const mapped = tagTranslationMap[name]?.[language];
  if (mapped) return mapped;
  
  if (language === "en" && slug) {
    return slug
      .split("-")
      .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
      .join(" ");
  }
  return name;
};
